#!/usr/bin/env python3
"""Independent known-answer vectors for the host harness, computed with Python's hmac module from the REAL keys in
rpi3_can_monitor_keys.h. They prove that the harness's mock HMAC-SHA256 and the monitor's message layouts agree with an
independent implementation (so the tests are not circular). Writes vectors.h."""
import hmac, hashlib, re, struct, os
HERE = os.path.dirname(os.path.abspath(__file__))
KEYS = open(os.path.join(HERE, '../../../optee_full/optee_os/core/arch/arm/plat-rpi3/rpi3_can_monitor_keys.h')).read()
def key(name):
    m = re.search(r'#define RPI3_MON_KEY_%s_INIT \{(.*?)\n\}' % name, KEYS, re.S)
    b = bytes(int(x, 16) for x in re.findall(r'0x[0-9a-f]{2}', m.group(1))); assert len(b) == 32; return b
KF, KH = key('FRAME'), key('HB')
def arr(n, b): return "static const unsigned char %s[%d] = {%s};\n" % (n, len(b), ", ".join("0x%02x" % x for x in b))
out = "/* generated by gen_vectors.py: independent known answers, do not edit */\n"
# command 17: a frame for can_id 0x123, counter 100, payload AA BB CC DD
head = struct.pack('<III', 0x123, 100, 0xDDCCBBAA)
tag = hmac.new(KF, head, hashlib.sha256).digest()
out += arr("VEC_FRAME_HEAD12", head) + arr("VEC_FRAME_TAG", tag)
# command 22: nonce for boot_id 0x11223344, hb_seq 7, issue_ticks 0x0000000123456789
inp = struct.pack('<IIQ', 0x11223344, 7, 0x0000000123456789)
nonce = hmac.new(KH, inp, hashlib.sha256).digest()[:8]
out += arr("VEC_NONCE_INPUT", inp) + arr("VEC_NONCE", nonce)
# boot_id: init_ticks 1000000060 and the mock RNG bytes 5A A5
bi = struct.pack('<Q', 1000000060) + bytes([0x5A, 0xA5])
out += arr("VEC_BOOTID_INPUT", bi) + "#define VEC_BOOTID 0x%08xu\n" % struct.unpack('<I', hmac.new(KH, bi, hashlib.sha256).digest()[:4])[0]
# RFC 4231 test case 2 (checks the mock HMAC itself)
out += arr("RFC4231_2_KEY", b"Jefe") + arr("RFC4231_2_DATA", b"what do ya want for nothing?") + arr("RFC4231_2_MAC", hmac.new(b"Jefe", b"what do ya want for nothing?", hashlib.sha256).digest())
open(os.path.join(HERE, 'vectors.h'), 'w').write(out)
print("vectors.h written;", len(out), "bytes")
